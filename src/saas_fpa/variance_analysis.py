"""Simulates realistic Year 3 "actuals" against the Year 3 budget, and
performs budget-vs-actual variance analysis.

The actuals are generated by re-running the *same* simulation engine used
to build the budget, but perturbing the underlying drivers each month with
random noise (bookings growth, churn, ACV, program spend, other opex) plus
a chance of a hiring delay — rather than perturbing the output line items
directly. This keeps the "actual" run internally consistent (it still ties
out as a full three-statement model) and means variance has a genuine
operating-driver story behind it, not just noise sprinkled on a P&L.

Variance analysis follows standard FP&A convention:
* **Variance $** = actual - budget
* **Variance %** = variance $ / |budget|
* **Materiality flag** = breaches *both* a % threshold and a $ threshold
  (avoids flagging trivial dollar swings on a tiny base, or modest %
  swings on a huge base)
* **Driver categorization** — volume, price/rate, or timing — decomposes
  *why* a line item missed, which is the difference between a variance
  report and a spreadsheet of red and green cells.
"""
from __future__ import annotations

import copy

import numpy as np
import pandas as pd

from .assumptions import OperatingAssumptions
from .data_generator import NoiseFn, SimState, run_months

LINE_ITEMS = [
    "revenue",
    "new_bookings_arr",
    "cogs",
    "gross_profit",
    "opex_sm",
    "opex_rd",
    "opex_ga",
    "total_opex",
    "ebitda",
    "net_income",
]


# Deliberate, named driver events layered on top of the baseline random
# noise for two months of the Year 3 budget year (relative to
# ``a.budget_year_start_month``, so +3 = the 4th month of the budget year).
# These aren't noise — they're the kind of discrete operating decisions a
# real variance narrative traces back to, and they're what
# ``variance_analysis`` surfaces as the concrete driver examples: a
# deliberate paid-acquisition push that both grew bookings and overspent
# the S&M budget, and a senior engineering hire that fell through and
# pushed R&D two months behind plan.
SCRIPTED_DRIVER_EVENTS = {
    3: {"program_spend_add": 0.32, "growth_add": 0.14, "label": "Q2 paid-acquisition push"},
    7: {"force_delay_hiring": True, "label": "senior engineering hire fell through"},
    8: {"force_delay_hiring": True, "label": "engineering hire still open"},
}


def _noise_fn_factory(a: OperatingAssumptions) -> NoiseFn:
    def noise_fn(month: int, rng: np.random.Generator) -> dict:
        mults = {
            "growth": 1.0 + rng.normal(0, a.noise_std_new_bookings_growth),
            "churn": 1.0 + rng.normal(0, a.noise_std_churn),
            "acv": 1.0 + rng.normal(0, a.noise_std_acv),
            "program_spend": 1.0 + rng.normal(0, a.noise_std_program_spend),
            "other_opex": 1.0 + rng.normal(0, a.noise_std_other_opex),
            "delay_hiring": rng.random() < a.hiring_delay_prob,
        }
        event = SCRIPTED_DRIVER_EVENTS.get(month - a.budget_year_start_month)
        if event:
            mults["program_spend"] += event.get("program_spend_add", 0.0)
            mults["growth"] += event.get("growth_add", 0.0)
            if event.get("force_delay_hiring"):
                mults["delay_hiring"] = True
        return mults

    return noise_fn


def simulate_year3_actuals(
    a: OperatingAssumptions, state_at_budget_start: SimState, capture_at: set | None = None
) -> tuple[pd.DataFrame, dict]:
    """Simulate Year 3 "actuals" from an independent copy of the same
    starting state used for the Year 3 budget, with noisy drivers.

    Returns ``(actual_df, snapshots)`` — ``snapshots`` holds deep-copied
    ``SimState`` objects for any month in ``capture_at``, for branching a
    forecast off the realized-actuals path (see ``cash_flow_forecast.py``).
    """
    state = copy.deepcopy(state_at_budget_start)
    rng = np.random.default_rng(a.variance_random_seed)
    noise_fn = _noise_fn_factory(a)
    actual, _, snapshots = run_months(
        a,
        range(a.budget_year_start_month, a.budget_year_end_month + 1),
        state,
        noise_fn=noise_fn,
        rng=rng,
        capture_at=capture_at,
    )
    return actual, snapshots


def _categorize_revenue_driver(budget_row: pd.Series, actual_row: pd.Series) -> tuple[str, str]:
    budget_customers = budget_row["customers_ending"]
    actual_customers = actual_row["customers_ending"]
    budget_price = budget_row["mrr_ending"] / budget_customers if budget_customers else 0.0
    actual_price = actual_row["mrr_ending"] / actual_customers if actual_customers else 0.0

    volume_effect = (actual_customers - budget_customers) * budget_price
    price_effect = (actual_price - budget_price) * actual_customers

    if abs(volume_effect) >= abs(price_effect):
        driver = "volume"
        note = (
            f"customer count {'beat' if actual_customers >= budget_customers else 'missed'} budget "
            f"({int(actual_customers)} vs {int(budget_customers)} planned)"
        )
    else:
        driver = "price/rate"
        note = f"average revenue per customer moved (${actual_price:,.0f} vs ${budget_price:,.0f} planned)"
    return driver, note


def _categorize_new_bookings_driver(budget_row: pd.Series, actual_row: pd.Series) -> tuple[str, str]:
    b_new, a_new = budget_row["customers_new"], actual_row["customers_new"]
    b_acv, a_acv = budget_row["new_customer_acv"], actual_row["new_customer_acv"]
    volume_effect = (a_new - b_new) * b_acv
    price_effect = (a_acv - b_acv) * a_new
    if abs(volume_effect) >= abs(price_effect):
        driver = "volume"
        note = f"new-logo count {'beat' if a_new >= b_new else 'missed'} plan ({int(a_new)} vs {int(b_new)} planned)"
    else:
        driver = "price/rate"
        note = f"new-customer ACV moved (${a_acv:,.0f} vs ${b_acv:,.0f} planned)"
    return driver, note


def _categorize_opex_driver(dept: str, budget_row: pd.Series, actual_row: pd.Series) -> tuple[str, str]:
    hc_col = {"opex_sm": "headcount_sm", "opex_rd": "headcount_rd", "opex_ga": "headcount_ga"}.get(dept)
    if hc_col and actual_row[hc_col] != budget_row[hc_col]:
        driver = "timing"
        note = (
            f"headcount {'ahead of' if actual_row[hc_col] > budget_row[hc_col] else 'behind'} plan "
            f"({int(actual_row[hc_col])} vs {int(budget_row[hc_col])} budgeted heads) — a hiring timing shift"
        )
        return driver, note
    driver = "price/rate"
    note = "headcount on plan; variance driven by non-headcount program/other spend"
    return driver, note


def build_variance_table(
    budget: pd.DataFrame, actual: pd.DataFrame, a: OperatingAssumptions
) -> pd.DataFrame:
    budget = budget.set_index("month")
    actual = actual.set_index("month")
    rows = []
    for month in budget.index:
        b_row, act_row = budget.loc[month], actual.loc[month]
        for item in LINE_ITEMS:
            b_val, a_val = float(b_row[item]), float(act_row[item])
            variance = a_val - b_val
            variance_pct = variance / abs(b_val) if b_val != 0 else np.nan
            material = (abs(variance) > a.materiality_threshold_abs) and (
                not np.isnan(variance_pct) and abs(variance_pct) > a.materiality_threshold_pct
            )
            if item == "revenue":
                driver, note = _categorize_revenue_driver(b_row, act_row)
            elif item == "new_bookings_arr":
                driver, note = _categorize_new_bookings_driver(b_row, act_row)
            elif item in ("opex_sm", "opex_rd", "opex_ga"):
                driver, note = _categorize_opex_driver(item, b_row, act_row)
            else:
                driver, note = "derived", "roll-up of underlying line items"
            rows.append(
                dict(
                    month=month,
                    line_item=item,
                    budget=b_val,
                    actual=a_val,
                    variance=variance,
                    variance_pct=variance_pct,
                    material=material,
                    driver_category=driver,
                    note=note,
                )
            )
    return pd.DataFrame(rows)


def variance_summary(variance_table: pd.DataFrame) -> dict:
    total_items = len(variance_table)
    material_items = int(variance_table["material"].sum())
    rev = variance_table[variance_table["line_item"] == "revenue"]
    opex = variance_table[variance_table["line_item"] == "total_opex"]
    return {
        "total_line_items_analyzed": total_items,
        "material_breaches": material_items,
        "material_breach_pct": material_items / total_items if total_items else 0.0,
        "total_revenue_budget": float(rev["budget"].sum()),
        "total_revenue_actual": float(rev["actual"].sum()),
        "total_revenue_variance": float(rev["variance"].sum()),
        "total_revenue_variance_pct": float(rev["variance"].sum() / rev["budget"].sum()) if rev["budget"].sum() else None,
        "total_opex_budget": float(opex["budget"].sum()),
        "total_opex_actual": float(opex["actual"].sum()),
        "total_opex_variance": float(opex["variance"].sum()),
        "total_opex_variance_pct": float(opex["variance"].sum() / opex["budget"].sum()) if opex["budget"].sum() else None,
    }


def top_material_examples(variance_table: pd.DataFrame, n: int = 3) -> pd.DataFrame:
    material = variance_table[variance_table["material"] & (variance_table["line_item"] != "gross_profit")]
    return material.reindex(material["variance"].abs().sort_values(ascending=False).index).head(n)
